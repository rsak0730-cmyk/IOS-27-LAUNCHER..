package com.newlauncher.core.designsystem.tokens

import androidx.compose.ui.unit.dp

/**
 * Layer 1 — Radius tokens.
 *
 * A soft, rounded scale. Larger radii are used for glass cards and panels so
 * that edge refraction reads naturally at the corners.
 */
object RadiusTokens {
    val None = 0.dp
    val Xs = 4.dp
    val Sm = 8.dp
    val Md = 12.dp
    val L = 16.dp
    val Xl = 20.dp
    val Xxl = 24.dp
    val Pill = 999.dp
}
